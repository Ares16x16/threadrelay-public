"""Collection boundary for an exclusively app-owned, visible Chromium session.

There is intentionally NO Python browser-process launcher or arbitrary CDP URL
API here. Playwright's raw launcher creates detached groups not contained by the
host's worker group. The default is unavailable until a native host adapter
satisfies AppOwnedBrowserLauncher/OwnedBrowserLease (see docs/collector.md).
"""
from collections.abc import Callable
from datetime import datetime, timezone
from pathlib import Path
import re
from typing import Literal, Protocol, TypedDict
from urllib.parse import urlsplit

from playwright.sync_api import BrowserContext, Error as PlaywrightError, Page

from threadrelay.collector.canonicalize import HOSTS
from threadrelay.collector.extractor import CARD_SELECTOR, RENDERED_SNAPSHOT_JS, ExtractionIssue, ObservedPost, captured_snapshot_fingerprint, issue, post_from_snapshot
from threadrelay.contracts import validate_contract

LeaseStatus = Literal["active", "disconnected", "ownership_lost"]


class ShutdownReport(TypedDict):
    stopped: bool
    remaining: list[str]


class OwnedBrowserLease(Protocol):
    """Trusted host capability, never constructed from renderer/PID/URL data.

    Native adapter owns the process and a dedicated persistent profile/context.
    `page` is exactly one app-owned page in `context`; source_session_id is newly
    generated by that adapter for this activation. poll() consults opaque native
    process ownership, not only the network connection. close() requests bounded
    native owned shutdown, retaining unconfirmed handles for later cleanup.
    """
    @property
    def context(self) -> BrowserContext: ...
    @property
    def page(self) -> Page: ...
    @property
    def profile_dir(self) -> Path: ...
    @property
    def source_session_id(self) -> str: ...
    def poll(self) -> LeaseStatus: ...
    def close(self) -> ShutdownReport: ...


class AppOwnedBrowserLauncher(Protocol):
    """Internal DI only; no IPC command accepts an implementation or endpoint.

    Must delegate direct Chromium launch through the native same-manager owned
    worker capability BEFORE activation, use only the locked dedicated profile,
    and supply a visible (headed) persistent context. A local Playwright CDP
    attachment is permitted ONLY to the native-verified endpoint of that exact
    owned process. No arbitrary endpoint, default profile, nested raw Playwright
    launch, cloud browser, or `trusted=True` escape satisfies this contract.
    """
    def open(self, profile_dir: Path, *, feed_url: str) -> OwnedBrowserLease: ...


class BrowserUnavailable(RuntimeError):
    pass


class BrowserShutdownUnconfirmed(RuntimeError):
    pass


_CHALLENGE_JS = """() => [...document.querySelectorAll(
    'form input[type=password], [role=dialog][aria-label="Log in"], '
    + '[role=dialog][aria-label="Security check"], [role=alert][aria-label="Account warning"]'
)].some(el => el.getClientRects().length && getComputedStyle(el).visibility!=='hidden')"""
_SCROLL_JS = "() => window.scrollBy({top: Math.max(1, Math.floor(innerHeight * 0.65)), behavior: 'instant'})"
MAX_SNAPSHOT_CARDS = 100


def _feed_url(url: str) -> str:
    if not isinstance(url, str) or len(url) > 4096 or re.search(r"[\s\\%\x00-\x1f\x7f]", url):
        raise ValueError("unsupported_feed_url")
    try:
        parsed = urlsplit(url)
        if (parsed.scheme != "https" or parsed.hostname not in HOSTS or parsed.username
                or parsed.password or parsed.port is not None or parsed.query or parsed.fragment
                or not re.fullmatch(r"/(?:@[A-Za-z0-9_.]{1,30}/?)?", parsed.path)):
            raise ValueError("unsupported_feed_url")
    except ValueError:
        raise ValueError("unsupported_feed_url") from None
    return url


class BrowserSession:
    """Bounded synchronous collector; session controller owns the intake gate.

    Caller supplies trusted app-data path, launch adapter and lifecycle callbacks
    in worker code, never renderer JSON. Default can_intake denies all collection.
    No callback or collection run implicitly starts/resumes/relaunches a session.
    """
    def __init__(self, *, app_data_dir: Path, launcher: AppOwnedBrowserLauncher | None = None,
                 feed_url: str = "https://www.threads.com/", can_intake: Callable[[], bool] = lambda: False,
                 on_attention: Callable[[str], None] = lambda reason: None,
                 now: Callable[[], datetime] = lambda: datetime.now(timezone.utc)):
        if not app_data_dir.is_absolute():
            raise ValueError("app_data_dir_must_be_absolute")
        self._profile = app_data_dir.resolve() / "browser-profiles" / "threads"
        self._launcher = launcher
        self._feed_url = _feed_url(feed_url)
        self._can_intake = can_intake
        self._on_attention = on_attention
        self._now = now
        self._lease: OwnedBrowserLease | None = None
        self._paused_reason: str | None = None
        self._pending: dict[str, ObservedPost] = {}
        self._seen: dict[str, str] = {}
        self._issues: list[ExtractionIssue] = []

    @property
    def issues(self) -> list[ExtractionIssue]:
        return [dict(value) for value in self._issues]

    def open(self, profile_dir: Path) -> None:
        if self._lease is not None:
            raise BrowserUnavailable("browser_already_open")
        if not profile_dir.is_absolute() or profile_dir.resolve() != self._profile:
            raise ValueError("dedicated_profile_required")
        # Do not follow an app-profile subtree redirected to a normal browser.
        if any(path.is_symlink() for path in (profile_dir, profile_dir.parent)):
            raise ValueError("dedicated_profile_symlink")
        if self._launcher is None:
            raise BrowserUnavailable("native_owned_browser_launcher_unavailable")
        lease = self._launcher.open(profile_dir, feed_url=self._feed_url)
        # Retain ownership BEFORE validation so a mismatch cannot lose cleanup.
        self._lease = lease
        try:
            if (lease.profile_dir.resolve() != self._profile or lease.page.context is not lease.context
                    or lease.poll() != "active" or not isinstance(lease.source_session_id, str)
                    or not 1 <= len(lease.source_session_id) <= 128):
                raise BrowserUnavailable("owned_browser_identity_mismatch")
        except Exception:
            self.close()
            raise
        self._paused_reason = None
        self._pending.clear()
        self._seen.clear()
        self._issues.clear()

    def _pause(self, reason: str) -> None:
        if self._paused_reason is None:
            self._paused_reason = reason  # close local gate before external callback
            self._pending.clear()
            self._on_attention(reason)

    def _ready(self) -> bool:
        lease = self._lease
        if lease is None or self._paused_reason is not None or not self._can_intake():
            return False
        # Native/IPC bindings can raise any ordinary Exception. Isolate only
        # this ownership probe; BaseException cancellation/exit signals escape.
        try:
            status = lease.poll()
        except Exception:
            self._pause("browser_ownership_lost")
            return False
        try:
            if status != "active":
                self._pause("browser_lost" if status == "disconnected" else "browser_ownership_lost")
                return False
            if lease.page.is_closed():
                self._pause("browser_lost")
                return False
            parsed = urlsplit(lease.page.url)
            if parsed.hostname in HOSTS and any(part in {"login", "challenge", "checkpoint"} for part in parsed.path.split("/")):
                self._pause("manual_login_or_challenge")
                return False
            try:
                _feed_url(lease.page.url)
            except ValueError:
                self._pause("unexpected_navigation")
                return False
            if lease.page.evaluate(_CHALLENGE_JS):
                self._pause("manual_login_or_challenge")
                return False
            return True
        except OSError:
            self._pause("browser_ownership_lost")
            return False
        except PlaywrightError:
            self._pause("browser_lost")
            return False

    def _capture(self) -> None:
        if not self._ready():
            return
        assert self._lease is not None
        try:
            snapshots = self._lease.page.locator(CARD_SELECTOR).evaluate_all(
                f"cards => cards.length > {MAX_SNAPSHOT_CARDS} ? [{{issue: 'snapshot_limit'}}] : cards.map({RENDERED_SNAPSHOT_JS})")
            if not snapshots:
                self._issues = [issue("unknown_layout")]
                self._pause("unknown_layout")
                return
            if len(snapshots) > MAX_SNAPSHOT_CARDS:
                self._issues = [issue("snapshot_limit")]
                self._pause("snapshot_limit")
                return
            observed_at = self._now()
            posts = [post_from_snapshot(raw, source_session_id=self._lease.source_session_id, observed_at=observed_at) for raw in snapshots]
            self._issues = [post for post in posts if "code" in post and post["code"] != "not_visible"]
            fatal = next((value["code"] for value in self._issues if value["code"] == "snapshot_limit" or (value["code"] == "unknown_layout" and not any("post_id" in post for post in posts))), None)
            if fatal is not None:
                self._pause(fatal)
                return
            # Pause/stop/caps may have closed intake during the DOM read.
            if not self._can_intake():
                self._pending.clear()
                return
            for post in posts:
                if "post_id" not in post:
                    continue
                if self._seen.get(post["post_id"]) == captured_snapshot_fingerprint(post):
                    # A newer snapshot can revert to the last emitted data.
                    # Reconcile it before dedup, so an older buffered edit cannot
                    # become the current observation after this read.
                    self._pending.pop(post["post_id"], None)
                    continue
                if len(self._pending) >= MAX_SNAPSHOT_CARDS and post["post_id"] not in self._pending:
                    self._pause("snapshot_limit")
                    return
                self._pending[post["post_id"]] = post
        except PlaywrightError:
            self._pause("browser_lost")

    def observe(self) -> list[ObservedPost]:
        self._capture()
        if not self._ready():
            self._pending.clear()
            return []
        result = list(self._pending.values())
        self._pending.clear()
        for post in result:
            self._seen[post["post_id"]] = captured_snapshot_fingerprint(post)
        return result

    def scroll_next(self) -> None:
        # Capture BEFORE the scroll event can detach/recycle virtualized cards.
        self._capture()
        if not self._ready():
            return
        assert self._lease is not None
        try:
            self._lease.page.evaluate(_SCROLL_JS)
        except PlaywrightError:
            self._pause("browser_lost")

    def close(self) -> None:
        if self._lease is None:
            return
        self._paused_reason = self._paused_reason or "browser_closed"
        self._pending.clear()
        try:
            report = self._lease.close()
            validate_contract("ShutdownReport", report)
            if not report["stopped"] or report["remaining"]:
                raise BrowserShutdownUnconfirmed("browser_shutdown_unconfirmed")
        except Exception as error:
            # Keep lease for explicit later native cleanup/confirmation.
            self._paused_reason = "browser_shutdown_unconfirmed"
            self._on_attention("browser_shutdown_unconfirmed")
            raise BrowserShutdownUnconfirmed("browser_shutdown_unconfirmed") from error
        self._lease = None
